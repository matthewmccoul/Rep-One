"""Generate include/mordor/game_data.h and src/game_data_json.cpp from data/combat-data.json (exact mirror of the tables).
usage: gen_data.py <code dir>"""
import json, re, sys
C = sys.argv[1]
d = json.load(open(f"{C}/data/combat-data.json"))
def cpp_type(v):
    if isinstance(v, bool): return "bool"
    if isinstance(v, int): return "i32"
    if isinstance(v, float): return "double"
    if isinstance(v, str): return "Str"
    raise ValueError(type(v))
def struct_for(name, sample):
    fields = []
    for k, v in sample.items():
        if isinstance(v, list):
            fields.append((k, f"Arr<{cpp_type(v[0])}, {len(v)}>", ("array", cpp_type(v[0]), len(v))))
        else: fields.append((k, cpp_type(v), ("scalar", cpp_type(v))))
    return name, fields
def merged_sample(rows):   # a row with every key; float wins over int when mixed
    s = {}
    for r in rows:
        for k, v in r.items():
            if k not in s or (isinstance(s[k], int) and isinstance(v, float)): s[k] = v
            elif isinstance(v, list) and isinstance(s[k], list) and any(isinstance(x, float) for x in v):
                s[k] = [0.5] * len(s[k])
    return s
tables = [("RaceDef", "races"), ("GuildDef", "guilds"), ("SpellDef", "spells"), ("ItemDef", "items"), ("MonsterDef", "monsters"),
          ("NamedEntry", "itemTypes"), ("NamedEntry", "itemDescriptions"), ("NamedEntry", "monsterClasses"), ("NamedEntry", "monsterGroups")]
structs = {}
for sname, key in tables:
    if sname not in structs: structs[sname] = struct_for(sname, merged_sample(d[key]))
fl = d["floors"][0]
structs["FloorField"] = struct_for("FloorField", fl["fields"][0]); structs["FloorArea"] = struct_for("FloorArea", fl["areas"][0])
structs["FloorTeleporter"] = struct_for("FloorTeleporter", fl["teleporters"][0]); structs["FloorChute"] = struct_for("FloorChute", fl["chutes"][0])
h = ["// GENERATED by tools/gen_data.py from data/combat-data.json - do not edit by hand.", "// Plain data tables of the game (races, guilds, spells, items, monsters, floors). Field names match the data file.",
     "#pragma once", '#include "mordor/types.h"', "", "namespace mordor {", ""]
order = ["RaceDef", "GuildDef", "SpellDef", "ItemDef", "MonsterDef", "NamedEntry", "FloorField", "FloorArea", "FloorTeleporter", "FloorChute"]
for sname in order:
    h.append(f"struct {sname} {{")
    for fname, ftype, _ in structs[sname][1]:
        init = "" if ftype.startswith("Arr") or ftype == "Str" else (" = 0" if ftype != "bool" else " = false")
        if ftype.startswith("Arr"): init = " = {}"
        h.append(f"  {ftype} {fname}{init};")
    h.append("};\n")
h += ["struct FloorDef {", "  i32 areasInUse = 0;", "  i32 width = 0;", "  i32 height = 0;", "  i32 levelNum = 0;", "  i32 headerAreaCount = 0;",
      "  Vec<FloorField> fields;   // width*height squares, index = y*width + x (see the SRD, chapter 15)", "  Vec<FloorArea> areas;", "  Vec<FloorTeleporter> teleporters;", "  Vec<FloorChute> chutes;", "};\n"]
h.append("// Bit positions of FloorField::flags.\nenum FloorFlag : int {")
for k, v in d["floorFlagBits"].items(): h.append(f"  FLAG_{k} = {v},")
h.append("};\n")
h += ["struct GameData {", "  Vec<RaceDef> races;", "  Vec<GuildDef> guilds;", "  Vec<SpellDef> spells;", "  Vec<ItemDef> items;", "  Vec<MonsterDef> monsters;",
      "  Vec<NamedEntry> itemTypes;", "  Vec<NamedEntry> itemDescriptions;", "  Vec<NamedEntry> monsterClasses;", "  Vec<NamedEntry> monsterGroups;", "  Vec<FloorDef> floors;", "};\n",
      "// Fills GameData from the text of combat-data.json. Returns false and sets err on failure.", "bool loadGameDataFromJson(const Str& jsonText, GameData& out, Str& err);", "", "}  // namespace mordor", ""]
open(f"{C}/include/mordor/game_data.h", "w").write("\n".join(h))
c = ['// GENERATED by tools/gen_data.py - do not edit by hand.', '#include "mordor/game_data.h"', '#include "mordor/json_lite.h"', "", "namespace mordor {", "namespace {", "",
     "i32 geti(const JsonValue& o, const char* k) { const JsonValue* v = o.find(k); return v ? static_cast<i32>(v->asInt()) : 0; }",
     "double getd(const JsonValue& o, const char* k) { const JsonValue* v = o.find(k); return v ? v->asDouble() : 0.0; }",
     "bool getb(const JsonValue& o, const char* k) { const JsonValue* v = o.find(k); return v ? v->asBool() : false; }",
     "Str gets(const JsonValue& o, const char* k) { const JsonValue* v = o.find(k); return v ? v->asString() : Str(); }",
     "template <class T, std::size_t N> void getarr(const JsonValue& o, const char* k, Arr<T, N>& a) {",
     "  const JsonValue* v = o.find(k);", "  if (!v) return;", "  for (std::size_t i = 0; i < N && i < v->arr.size(); ++i) a[i] = static_cast<T>(v->arr[i].asDouble());", "}", ""]
for sname in order:
    c.append(f"void read{sname}(const JsonValue& o, {sname}& r) {{")
    for fname, ftype, kind in structs[sname][1]:
        if kind[0] == "array": c.append(f'  getarr(o, "{fname}", r.{fname});')
        elif ftype == "i32": c.append(f'  r.{fname} = geti(o, "{fname}");')
        elif ftype == "double": c.append(f'  r.{fname} = getd(o, "{fname}");')
        elif ftype == "bool": c.append(f'  r.{fname} = getb(o, "{fname}");')
        else: c.append(f'  r.{fname} = gets(o, "{fname}");')
    c.append("}\n")
c += ["template <class T, class F> void readList(const JsonValue* v, Vec<T>& out, F f) {", "  if (!v) return;", "  for (const auto& e : v->arr) { T t; f(e, t); out.push_back(std::move(t)); }", "}", "", "}  // namespace", "",
      "bool loadGameDataFromJson(const Str& jsonText, GameData& out, Str& err) {", "  JsonValue root;", "  if (!parseJson(jsonText, root, err)) return false;",
      '  if (root.type != JsonValue::Type::Object) { err = "root is not an object"; return false; }', "  out = GameData();"]
for key, sname, field in [("races", "RaceDef", "races"), ("guilds", "GuildDef", "guilds"), ("spells", "SpellDef", "spells"), ("items", "ItemDef", "items"), ("monsters", "MonsterDef", "monsters"),
                          ("itemTypes", "NamedEntry", "itemTypes"), ("itemDescriptions", "NamedEntry", "itemDescriptions"), ("monsterClasses", "NamedEntry", "monsterClasses"), ("monsterGroups", "NamedEntry", "monsterGroups")]:
    c.append(f'  readList(root.find("{key}"), out.{field}, read{sname});')
c += ['  if (const JsonValue* fl = root.find("floors")) {', "    for (const auto& fo : fl->arr) {", "      FloorDef f;", "      f.areasInUse = geti(fo, \"areasInUse\"); f.width = geti(fo, \"width\"); f.height = geti(fo, \"height\");",
      "      f.levelNum = geti(fo, \"levelNum\"); f.headerAreaCount = geti(fo, \"headerAreaCount\");",
      '      readList(fo.find("fields"), f.fields, readFloorField); readList(fo.find("areas"), f.areas, readFloorArea);',
      '      readList(fo.find("teleporters"), f.teleporters, readFloorTeleporter); readList(fo.find("chutes"), f.chutes, readFloorChute);',
      "      out.floors.push_back(std::move(f));", "    }", "  }", "  return true;", "}", "", "}  // namespace mordor", ""]
open(f"{C}/src/game_data_json.cpp", "w").write("\n".join(c))
print("generated", len(h), "header lines,", len(c), "source lines")
