#!/usr/bin/env python3
"""Copy the engine-neutral core and its data files into the Unreal plugin folder.

  sync_core_into_plugin.py [--code-dir DIR] [--work-dir DIR] [--plugin-dir DIR] [--log FILE]

Defaults come from this script's location: code dir = <this>/.., work dir = <code dir>/.., plugin dir =
<code dir>/unreal/DelveDeeperContent.

Core headers (common, map, puzzle, quest: include/dd/*.h) -> Source/DelveDeeperContent/Public/Core/dd/
Core sources (src/*.cpp)                                  -> Source/DelveDeeperContent/Private/Core/
Both get a first-line banner "generated, do not edit"; the rest is byte-identical to the source.
Data files (map, puzzle, quest JSON and strings CSV)      -> Content/Data/ (byte-identical, no banner).

Repeatable: the generated Core folders are rebuilt each run. Fails loudly (exit 1, nothing written)
when any source is missing. Exit 2 on usage error.
"""
import os
import sys

CORE_DIRS = ["common", "map", "puzzle", "quest"]
DATA_FILES = [
    ("map", "floor1_map.json"),
    ("puzzle", "storeroom_puzzle.json"),
    ("quest", "figure_ore_lift_quest.json"),
    ("quest", "figure_ore_lift_strings.csv"),
]
MODULE = os.path.join("Source", "DelveDeeperContent")


def banner(rel_source):
    return ("// GENERATED by tools/sync_core_into_plugin.py from %s. Generated copy, do not edit; "
            "edit the source and run the script again.\n" % rel_source)


def main(argv):
    here = os.path.dirname(os.path.abspath(__file__))
    code = os.path.normpath(os.path.join(here, ".."))
    work = None
    plugin = None
    log = None
    args = argv[1:]
    i = 0
    while i < len(args):
        if args[i] in ("--code-dir", "--work-dir", "--plugin-dir", "--log") and i + 1 < len(args):
            v = args[i + 1]
            if args[i] == "--code-dir":
                code = os.path.abspath(v)
            elif args[i] == "--work-dir":
                work = os.path.abspath(v)
            elif args[i] == "--plugin-dir":
                plugin = os.path.abspath(v)
            else:
                log = v
            i += 2
        else:
            print("usage: sync_core_into_plugin.py [--code-dir DIR] [--work-dir DIR] [--plugin-dir DIR] [--log FILE]")
            return 2
    work = work or os.path.normpath(os.path.join(code, ".."))
    plugin = plugin or os.path.join(code, "unreal", "DelveDeeperContent")

    out = []
    missing = []
    plan = []  # (src, dst, kind)
    for d in CORE_DIRS:
        inc = os.path.join(code, d, "include", "dd")
        src = os.path.join(code, d, "src")
        heads = sorted(f for f in os.listdir(inc) if f.endswith(".h")) if os.path.isdir(inc) else []
        cpps = sorted(f for f in os.listdir(src) if f.endswith(".cpp")) if os.path.isdir(src) else []
        if not heads:
            missing.append("no headers in " + inc)
        if not cpps:
            missing.append("no sources in " + src)
        for f in heads:
            plan.append((os.path.join(inc, f),
                         os.path.join(plugin, MODULE, "Public", "Core", "dd", f), "header"))
        for f in cpps:
            plan.append((os.path.join(src, f),
                         os.path.join(plugin, MODULE, "Private", "Core", f), "source"))
    for d, f in DATA_FILES:
        p = os.path.join(work, d, f)
        if not os.path.isfile(p):
            missing.append("missing data file " + p)
        else:
            plan.append((p, os.path.join(plugin, "Content", "Data", f), "data"))

    if missing:
        for m in missing:
            out.append("ERROR: " + m)
        out.append("RESULT FAIL (nothing written)")
        return finish(out, log, 1)

    # Rebuild only the generated folders and the data files this script owns.
    for sub in (os.path.join(MODULE, "Public", "Core"), os.path.join(MODULE, "Private", "Core")):
        base = os.path.join(plugin, sub)
        if os.path.isdir(base):
            for dp, _dn, fn in os.walk(base):
                for name in fn:
                    os.remove(os.path.join(dp, name))
    count = {"header": 0, "source": 0, "data": 0}
    for src, dst, kind in plan:
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(src, "rb") as f:
            data = f.read()
        if kind != "data":
            rel = os.path.relpath(src, code).replace(os.sep, "/")
            data = banner(rel).encode("utf-8") + data
        with open(dst, "wb") as f:
            f.write(data)
        count[kind] += 1
        out.append("copied %-6s %s -> %s" % (kind, os.path.relpath(src, work), os.path.relpath(dst, code)))
    out.append("copied %d headers, %d sources, %d data files" % (count["header"], count["source"], count["data"]))
    out.append("RESULT PASS")
    return finish(out, log, 0)


def finish(lines, log, code):
    text = "\n".join(lines) + "\n"
    sys.stdout.write(text)
    if log:
        with open(log, "w", encoding="utf-8") as f:
            f.write(text)
    return code


if __name__ == "__main__":
    sys.exit(main(sys.argv))
